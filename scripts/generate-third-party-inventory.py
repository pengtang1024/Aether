#!/usr/bin/env python3
"""Generate docs/THIRD_PARTY_INVENTORY.md from Cargo metadata.

The inventory is evidence for licence review: every normal (compiled-in)
dependency of every workspace member, its SPDX expression and the release
targets that pull it in. It is generated, not hand-maintained:

    python3 scripts/generate-third-party-inventory.py

Build-only/proc-macro crates are not listed: they are not distributed in the
binary. License texts live in LICENSES/; Cargo.lock+the release SBOM pin the
exact versions.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "linux": "x86_64-unknown-linux-gnu",
    "windows": "x86_64-pc-windows-gnu",
    "macos": "aarch64-apple-darwin",
}
OUT = ROOT / "docs" / "THIRD_PARTY_INVENTORY.md"


def metadata() -> dict:
    env = dict(os.environ)
    env["RUSTC_WRAPPER"] = ""
    return json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--all-features"],
            cwd=ROOT,
            env=env,
        )
    )


def graph(target: str) -> set[tuple[str, str]]:
    env = dict(os.environ)
    env["RUSTC_WRAPPER"] = ""
    output = subprocess.check_output(
        [
            "cargo",
            "tree",
            "--workspace",
            "--all-features",
            "--target",
            target,
            "--edges",
            "normal",
            "--prefix",
            "none",
        ],
        cwd=ROOT,
        env=env,
        text=True,
        stderr=subprocess.DEVNULL,
    )
    found: set[tuple[str, str]] = set()
    for line in output.splitlines():
        line = line.split(" (*)")[0].strip()
        match = re.match(r"([A-Za-z0-9_.+-]+) v([0-9][^ ]*)", line)
        if match:
            found.add((match.group(1), match.group(2)))
    return found


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    meta = metadata()
    packages = {(p["name"], p["version"]): p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    targets = {
        label: {key for key in graph(target) if packages.get(key, {}).get("id") not in members}
        for label, target in TARGETS.items()
    }
    union = set().union(*targets.values())

    rows = []
    for key in sorted(union):
        package = packages.get(key)
        if package is None:
            continue
        used = [label for label, deps in targets.items() if key in deps]
        rows.append(
            (
                key[0],
                key[1],
                package.get("license") or "UNKNOWN",
                "/".join(used),
                package.get("repository") or "",
            )
        )

    counts = Counter(row[2] for row in rows)
    lines = [
        "# Third-party dependency inventory",
        "",
        "> Generated by `scripts/generate-third-party-inventory.py`; do not edit by hand.",
        "> Normal (compiled-in) dependencies of every workspace member, across the",
        "> Linux, Windows and macOS release targets. Build-only/proc-macro crates are",
        "> excluded because they are not distributed in the binary. License texts are",
        "> in [`LICENSES/`](../LICENSES/); exact versions are pinned by `Cargo.lock` and",
        "> the release CycloneDX SBOM.",
        "",
        f"Total packages: **{len(rows)}**",
        "",
        "## By license",
        "",
        "| License | Packages |",
        "| --- | ---: |",
    ]
    for license, count in sorted(counts.items(), key=lambda item: (-item[1], item[0])):
        lines.append(f"| `{license}` | {count} |")

    lines += [
        "",
        "## Packages",
        "",
        "| Package | Version | License | Targets | Repository |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, version, license, used, repository in rows:
        repo = f"<{repository}>" if repository else ""
        lines.append(
            f"| `{name}` | `{version}` | `{license}` | {used} | {repo} |"
        )

    rendered = "\n".join(lines) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != rendered:
            print(f"FAIL: {OUT} is out of date; rerun the generator", file=sys.stderr)
            return 1
        print(f"OK: {OUT} is up to date")
        return 0
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

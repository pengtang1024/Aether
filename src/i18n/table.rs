//! Translation rows for languages other than the Chinese source and English.
//!
//! One row per Chinese source string: `(chinese, japanese, traditional)`.
//! `tr` pulls a row by the exact Chinese literal that opened the call site,
//! so a translation cannot drift away from its key; an empty cell (or a
//! missing row) falls back to Chinese instead of showing a blank string.
//! English is intentionally NOT here: it travels beside the call site in
//! `tr(zh, en)` — the pair is reviewed together at every site.

/// `(source-zh, japanese, traditional-chinese)` for [`ROWS`].
type Row = (&'static str, &'static str, &'static str);

fn cell(row: &Row, column: usize) -> Option<String> {
    let text = match column {
        0 => row.1,
        _ => row.2,
    };
    (!text.is_empty()).then(|| text.to_string())
}

/// Japanese translation of a Chinese source string, if a row exists.
pub fn lookup_ja(zh: &str) -> Option<String> {
    cell(ROWS.iter().find(|row| row.0 == zh)?, 0)
}

/// Traditional-Chinese translation, if a row exists.
pub fn lookup_zh_hant(zh: &str) -> Option<String> {
    cell(ROWS.iter().find(|row| row.0 == zh)?, 1)
}

/// Iterate rows for tests.
#[cfg(test)]
pub fn rows() -> impl Iterator<Item = Row> {
    ROWS.iter().copied()
}

